"""Build brand assets from public/brand/infin8x-logo.png (original kept untouched).
Outputs: webp variants, glass-rim image, and src/brand/logoGeometry.ts (path + sampled colours)."""
import cv2, numpy as np, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = os.path.join(ROOT, 'public', 'brand')
im = cv2.imread(os.path.join(B, 'infin8x-logo.png'), cv2.IMREAD_UNCHANGED)
H, W = im.shape[:2]
a = im[:, :, 3]
# premultiply-clean: zero colour where alpha==0 (removes stray colour in transparent pixels)
clean = im.copy(); clean[a == 0] = 0
for w in (1904, 1200, 720):
    out = clean if w == W else cv2.resize(clean, (w, round(H * w / W)), interpolation=cv2.INTER_AREA)
    cv2.imwrite(os.path.join(B, f'infin8x-logo-{w}.webp'), out, [cv2.IMWRITE_WEBP_QUALITY, 88])
# glass rim: thin bright edge where alpha transitions, plus soft inner sheen
af = a.astype(np.float32) / 255
k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7))
edge = np.clip(cv2.dilate(af, k) - cv2.erode(af, k), 0, 1)
edge = cv2.GaussianBlur(edge, (0, 0), 1.2)
inner = af - cv2.erode(af, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (25, 25)))
inner = cv2.GaussianBlur(np.clip(inner, 0, 1), (0, 0), 4) * 0.35
rim = np.clip(edge + inner, 0, 1) * af ** 0.2
rgba = np.dstack([np.full_like(a, 255)] * 3 + [(rim * 255).astype(np.uint8)])
cv2.imwrite(os.path.join(B, 'infin8x-rim.webp'), cv2.resize(rgba, (1200, round(H * 1200 / W)), interpolation=cv2.INTER_AREA), [cv2.IMWRITE_WEBP_QUALITY, 85])
# sample path & colours
P = json.load(open(os.path.join(ROOT, 'scripts', 'logo-path.json')))
import re
nums = [float(n) for n in re.findall(r'-?\d+\.?\d*', P['full'])]
start = np.array(nums[:2]); segs = []
cur = start; rest = nums[2:]
for i in range(0, len(rest) - 5, 6):
    c1, c2, p = np.array(rest[i:i+2]), np.array(rest[i+2:i+4]), np.array(rest[i+4:i+6])
    segs.append((cur, c1, c2, p)); cur = p
pts = []
for (p0, c1, c2, p1) in segs:
    for t in np.linspace(0, 1, 60, endpoint=False):
        pts.append((1-t)**3*p0 + 3*(1-t)**2*t*c1 + 3*(1-t)*t*t*c2 + t**3*p1)
pts.append(start); pts = np.array(pts)
d = np.r_[0, np.cumsum(np.linalg.norm(np.diff(pts, axis=0), axis=1))]
L = d[-1]; N = 720
s = np.linspace(0, L, N, endpoint=False)
xs = np.interp(s, d, pts[:, 0]); ys = np.interp(s, d, pts[:, 1])
blur = cv2.GaussianBlur(clean[:, :, :3].astype(np.float32), (0, 0), 14)
cols = []
for x, y in zip(xs, ys):
    b, g, r = blur[int(y), int(x)]
    m = max(r, g, b, 1); f = 255 / m  # normalise brightness -> pure hue light
    cols.append('%02x%02x%02x' % (int(r * f), int(g * f), int(b * f)))
# find split index (second pass through crossing)
cx, cy = P['cross']
dist = np.hypot(xs - cx, ys - cy)
half = int(np.argmin(dist[N//4: 3*N//4]) + N//4)
geo = {
  'viewBox': [W, H], 'cross': [round(cx, 1), round(cy, 1)], 'length': round(float(L), 1),
  'split': round(float(s[half] / L), 4),
  'pathFull': P['full'], 'pathRight': P['right'], 'pathLeft': P['left'],
  'samples': [[round(float(x), 1), round(float(y), 1)] for x, y in zip(xs, ys)],
  'colors': cols,
}
os.makedirs(os.path.join(ROOT, 'src', 'brand'), exist_ok=True)
with open(os.path.join(ROOT, 'src', 'brand', 'logoGeometry.ts'), 'w') as f:
    f.write('// GENERATED by scripts/build_assets.py from the logo artwork. Do not edit by hand.\n')
    f.write('// Coordinates are in the PNG\'s native pixel space (viewBox 0 0 %d %d).\n' % (W, H))
    f.write('export const LOGO_GEOMETRY = ' + json.dumps(geo, separators=(',', ':')) + ' as const;\n')
print('length', L, 'split', geo['split'], 'samples', N)
print('right-lobe first colours', cols[0:200:20]); print('left', cols[400:720:40])
